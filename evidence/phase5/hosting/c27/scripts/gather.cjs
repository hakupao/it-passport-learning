// S163 C27: dump context (stem/choices/answer + all three-language explanation fields) for the 27 jp-error candidates.
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../../../../..");
const J = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), "utf-8"));
const items = J("evidence/phase5/hosting/c20/round3_jp_errors.json").items;
const Q = Object.fromEntries(J("data/ip/quiz/questions.json").questions.map((q) => [q.id, q]));
const ex = (id) => id.slice(0, id.indexOf("-q"));
let out = "# C27 context (generated by scripts/gather.cjs)\n\n";
for (const [id, field, desc, border] of items) {
  const q = Q[id], e = J(`data/ip/quiz/explanations/${ex(id)}.json`).questions[id], t = J(`data/ip/quiz/translations/${ex(id)}.json`).questions[id];
  out += `## ${id} — ${field}${border ? " [border]" : ""}\n候補: ${desc}\n\n`;
  out += `- stem_jp: ${t.stem_jp_clean ?? q.stem_jp}\n- answer: ${q.correct_answer}${q.has_figure ? " (has_figure)" : ""}\n`;
  for (const [k, v] of Object.entries(q.choices_jp ?? {})) out += `- ${k}: ${v}\n`;
  const f = (lab, o) => { out += `\n### ${lab}\n- jp: ${o.jp}\n- zh: ${o.zh}\n- en: ${o.en}\n`; };
  f("correct", e.correct);
  for (const [k, o] of Object.entries(e.distractors ?? {})) f(`d:${k}`, o);
  (e.points ?? []).forEach((o, i) => f(`p:${i}`, o));
  out += "\n---\n\n";
}
fs.writeFileSync(path.join(ROOT, "evidence/phase5/hosting/c27/context.md"), out);
console.log(out.length);
