// D-217 H1-5 — out/_redirects for Cloudflare Workers static assets (developers.cloudflare.com/
// workers/static-assets/redirects/, 2026-11-11: `source destination code`, ≤ 2,000 static + 100
// dynamic rules, one splat, redirects win over an existing asset, the top-most matching line wins).
// What the next-intl middleware did on every request, minus language detection (D-219):
//   /                → /ja                     (302: the root's target stays changeable)
//   /<section>       → /ja/<section>           (301, the locale-less legacy links)
//   /<section>/*     → /ja/<section>/:splat
// Sections = the top-level routes the export emitted under out/ja (derived, never a catch-all: a
// catch-all would also catch /_next, /data, /quiz-figures, robots.txt …, which redirects beat).
// `?owner_key=` activation is not here: it needs the H3 Worker (cookies).

export function redirectsFile(sections: readonly string[]): string {
  const lines = ["# Generated by scripts/postexport.ts (src/lib/export/redirects.ts) — do not edit.", "/ /ja 302"];
  for (const s of sections) lines.push(`/${s} /ja/${s} 301`);
  for (const s of sections) lines.push(`/${s}/* /ja/${s}/:splat 301`);
  return lines.join("\n") + "\n";
}

const SECTION = /^[a-z][a-z0-9-]*$/;

/** Top-level route names of one locale tree: `out/ja/<x>.html` and `out/ja/<x>/`. */
export function sectionsOf(entries: readonly { name: string; isDir: boolean }[]): string[] {
  const names = new Set<string>();
  for (const e of entries) {
    const n = e.isDir ? e.name : e.name.replace(/\.html$/, "");
    if ((e.isDir || e.name.endsWith(".html")) && SECTION.test(n)) names.add(n);
  }
  return [...names].sort();
}

/** The source path of every rule (the splat as `*`). */
export function ruleSources(file: string): string[] {
  return file
    .split("\n")
    .filter((l) => l.trim() && !l.startsWith("#"))
    .map((l) => l.split(/\s+/)[0]!);
}
