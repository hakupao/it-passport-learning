// D-217 H1-5 — out/_headers for Cloudflare Workers static assets (developers.cloudflare.com/workers/
// static-assets/headers/, 2026-11-11: ≤ 100 rules, ≤ 2,000 chars a line, a request inherits every
// matching rule and a header set twice is comma-joined, so each header has exactly one rule here).
//
// - CSP (D-181 §0-8) on every path, as the next.config `headers` hook set it before the export. Static, so
//   script-src keeps 'unsafe-inline' for Next's inline flight scripts (self.__next_f.push); a nonce
//   needs a per-request response. Residual risk, accepted: connect-src (self + api.anthropic.com)
//   limits where fetch / XHR / WebSocket / sendBeacon can send data, but top-level navigation and
//   window.open are outside CSP, so an injected script can still carry the key out that way: any XSS
//   still means key exposure. style-src 'unsafe-inline' is for component style={{}}.
//   D-220: with a Web Analytics token the beacon script (static.cloudflareinsights.com) and its
//   endpoint (cloudflareinsights.com, manual embedding) are allowed — and only then.
// - Cache: /_next/static/* is content-hashed → one year, immutable. Everything else (HTML, /data/*,
//   /quiz-figures/*: names not hashed) keeps the platform default `public, max-age=0,
//   must-revalidate` + ETag (a revalidating cache), so no rule sets Cache-Control there.
// - Preview hosts: every *.workers.dev host (the worker URL `<name>.<sub>.workers.dev` and the
//   preview URLs `<version>-<name>.<sub>.workers.dev`, both two labels before workers.dev) gets
//   X-Robots-Tag: noindex. The custom domain matches no host rule. Responses made by Worker code
//   (H3) do not get _headers rules; the Worker sets its own.

export const BEACON_SCRIPT = "https://static.cloudflareinsights.com/beacon.min.js";
export const BEACON_ENDPOINT = "https://cloudflareinsights.com";

export function contentSecurityPolicy(analytics: boolean): string {
  return [
    "default-src 'self'",
    `script-src 'self' 'unsafe-inline'${analytics ? ` ${BEACON_SCRIPT}` : ""}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    `connect-src 'self' https://api.anthropic.com${analytics ? ` ${BEACON_ENDPOINT}` : ""}`,
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");
}

export const IMMUTABLE = "public, max-age=31536000, immutable";
export const PREVIEW_HOSTS = "https://:name.:subdomain.workers.dev/*";

export function headersFile(opts: { analytics: boolean }): string {
  return [
    "# Generated by scripts/postexport.ts (src/lib/export/headers.ts) — do not edit.",
    "/*",
    `  Content-Security-Policy: ${contentSecurityPolicy(opts.analytics)}`,
    "/_next/static/*",
    `  Cache-Control: ${IMMUTABLE}`,
    PREVIEW_HOSTS,
    "  X-Robots-Tag: noindex",
    "",
  ].join("\n");
}
