#!/usr/bin/env node
// S162 C20 step 5 (D-233 rule 3) — quiz zh quotes to the textbook / UI form: outermost quote → “”, a quote inside it → ‘’.
// Covers every zh string of the explanations (correct / distractors / points) and of the translations sidecar
// (stem / choices). Quote marks recognised: 「」『』“”‘’; each field must be balanced and at most 2 levels deep.
// Choice letters (「イ」), ASCII literals (「tmb」) and quoted Japanese / choice text get the same treatment (S162 sample check).
// Assumes no zh string uses ’ as an apostrophe (none in S162 data); one would stop the run as «unbalanced».
// Writes a patch list in the c20-quiz-apply.ts format (from = the whole field) — apply it with that script.
// Run: node --no-warnings scripts/c20-quiz-quotes.ts --out <patches.json>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const outAt = process.argv.indexOf("--out");
if (outAt < 0) throw new Error("--out <patches.json> is required");
type Row = Record<string, any>;
const OPEN: Record<string, string> = { "「": "」", "『": "』", "“": "”", "‘": "’" };
const CLOSERS = new Set(Object.values(OPEN));

export function curl(s: string, where: string): string {
  const stack: string[] = [];
  let out = "";
  for (const ch of s) {
    if (ch in OPEN) {
      if (stack.length >= 2) throw new Error(`${where}: quotes nested 3 deep`);
      out += stack.length === 0 ? "“" : "‘";
      stack.push(OPEN[ch]!);
    } else if (CLOSERS.has(ch)) {
      if (stack.pop() !== ch) throw new Error(`${where}: unbalanced ${ch}`);
      out += stack.length === 0 ? "”" : "’";
    } else out += ch;
  }
  if (stack.length) throw new Error(`${where}: unclosed quote`);
  return out;
}

const patches: Row[] = [];
const add = (id: string, where: string, v: unknown) => {
  if (typeof v !== "string") return;
  const after = curl(v, `${id} ${where}`);
  if (after !== v) patches.push({ id, where, lang: "zh", from: v, to: after });
};
const dir = (d: string) => path.join(ROOT, "data/ip/quiz", d);
for (const f of readdirSync(dir("explanations")).filter((x) => x.endsWith(".json")).sort()) {
  const d = JSON.parse(readFileSync(path.join(dir("explanations"), f), "utf-8"));
  for (const [id, q] of Object.entries<Row>(d.questions)) {
    add(id, "correct", q.correct?.zh);
    for (const [k, o] of Object.entries<Row>(q.distractors ?? {})) add(id, `d:${k}`, o?.zh);
    (q.points ?? []).forEach((o: Row, i: number) => add(id, `p:${i}`, o?.zh));
  }
}
for (const f of readdirSync(dir("translations")).filter((x) => x.endsWith(".json")).sort()) {
  const d = JSON.parse(readFileSync(path.join(dir("translations"), f), "utf-8"));
  for (const [id, q] of Object.entries<Row>(d.questions)) {
    add(id, "stem", q.stem?.zh);
    for (const [k, o] of Object.entries<Row>(q.choices ?? {})) add(id, `c:${k}`, o?.zh);
  }
}
const n = (re: RegExp) => patches.reduce((a, p) => a + (p.from.match(re) ?? []).length, 0);
console.log(JSON.stringify({ fields: patches.length, explanations: patches.filter((p) => !/^(stem|c:)/.test(p.where)).length, translations: patches.filter((p) => /^(stem|c:)/.test(p.where)).length, "「": n(/「/g), "『": n(/『/g), "“ kept-or-moved": n(/“/g) }));
writeFileSync(path.resolve(process.argv[outAt + 1]!), `${JSON.stringify({ note: "C20 step 5 (D-233 rule 3), generated by scripts/c20-quiz-quotes.ts", patches })}\n`);
